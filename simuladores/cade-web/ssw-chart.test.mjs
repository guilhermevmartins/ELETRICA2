import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {connectOverlappingTerminals} from './auto-connect.mjs';
import {simulate} from './engine.mjs';
import {rampPreview,recordRamp,rampChart} from './ssw-chart.mjs';
import {sswSettings} from './ssw05.mjs';
import {catalog,isMotor,motorRPM,validateProject} from './components.mjs';
const cfg=sswSettings({ssw:{initial:40,accel:2,decel:3,voltage:220}});
assert.deepEqual(rampPreview(cfg),[{t:0,v:0},{t:0,v:40},{t:2,v:100},{t:4,v:100},{t:7,v:0},{t:8,v:0}]);
assert.equal(rampPreview({...cfg,decel:0})[4].t,4);
const samples=[];for(let i=0;i<=12000;i++)recordRamp(samples,i/100,{voltage:75,phase:'full'});
assert.ok(samples.length<=610);assert.ok(samples.at(-1).t-samples[0].t>=59);
recordRamp(samples,120,{voltage:0,phase:'fault'});assert.equal(samples.at(-1).v,0);
assert.ok(!/NaN|Infinity/.test(rampChart(cfg,samples,true)));
assert.ok(!/NaN|Infinity/.test(rampChart(cfg,[],true)));
const motors=catalog.filter(isMotor);assert.ok(motors.length>=16);
assert.ok(!isMotor('native33297'));assert.ok(isMotor('motor'));assert.ok(isMotor('motor3'));assert.ok(isMotor('native33295'));assert.ok(isMotor('native33250'));
const project={format:'cade-web',version:1,components:motors.map((m,i)=>({id:'m'+i,type:m.type,x:200,y:200,rpm:1750})),wires:[]};
assert.ok(validateProject(project).components.every(c=>c.rpm===1750));
assert.equal(motorRPM({rpm:Infinity}),null);assert.equal(motorRPM({}),null);
assert.equal(motorRPM({rpm:.1}),null);
const example=validateProject(JSON.parse(readFileSync(new URL('./examples/ssw05.cadeweb.json',import.meta.url),'utf8')));
assert.equal(connectOverlappingTerminals(example,()=> 'unexpected'),0);
let state=simulate(example);assert.equal(state.shortCircuit,false);
state=simulate(example,state,{S1:true},1);assert.equal(state.softstarters.SSW1.phase,'accel');
state=simulate(example,state,{S1:true},5);assert.equal(state.softstarters.SSW1.voltage,100);
state=simulate(example,state,{},1);assert.equal(state.softstarters.SSW1.phase,'decel');
assert.equal(sswSettings({ssw:{voltage:9999}}).voltage,690);
console.log(`OK: rampas, histórico de 60 s, falha, gráfico vazio e RPM salvo nos ${motors.length} tipos de motor.`);
